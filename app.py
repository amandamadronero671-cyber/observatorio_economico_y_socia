def mapa_coropletico(df, indicador, anio):
    d = df[(df["indicador"] == indicador) & (df["anio"] == anio)].copy()
    if d.empty:
        fig = go.Figure()
        fig.add_annotation(text="Sin datos", x=0.5, y=0.5, showarrow=False)
        return fig, "Sin datos"
    d["lon"] = d["departamento"].map(lambda x: CENTROIDES.get(x, (None, None))[0])
    d["lat"] = d["departamento"].map(lambda x: CENTROIDES.get(x, (None, None))[1])
    d = d.dropna(subset=["lon", "lat"])
    fig = px.scatter_geo(d, lat="lat", lon="lon", size="valor", color="valor",
                         hover_name="departamento", hover_data={"valor": ":.2f", "lon": False, "lat": False},
                         color_continuous_scale="YlOrRd", size_max=45,
                         title=f"{indicador} – {anio}",
                         projection="natural earth", scope="south america")
    fig.update_geos(center=dict(lon=-74, lat=4.5), lataxis_range=[-5, 13], lonaxis_range=[-82, -66],
                    showland=True, landcolor="rgb(245,245,245)",
                    showcountries=True, countrycolor="gray")
    fig.update_layout(margin=dict(l=0, r=0, t=50, b=0), height=520)
    try:
        from scipy.spatial.distance import pdist, squareform
        coords = d[["lon", "lat"]].values
        dist = squareform(pdist(coords))
        w = 1 / (dist + 1e-6)
        np.fill_diagonal(w, 0)
        w = w / w.sum(axis=1, keepdims=True)
        z = (d["valor"] - d["valor"].mean()) / d["valor"].std()
        I = (len(z) / w.sum()) * (z @ w @ z) / (z @ z)
        texto = f"**Moran's I (global):** {I:.4f}\nValores > 0 → clustering espacial positivo."
    except Exception as e:
        texto = f"No se pudo calcular Moran's I: {e}"
    return fig, texto

def deep_learning_lstm(df, depto, indicador, epochs=30, lookback=3):
    if not HAS_TF:
        return "TensorFlow no disponible.", go.Figure()
    serie = get_series(df, depto, indicador)
    if len(serie) < lookback + 8:
        return f"Serie demasiado corta ({len(serie)} obs).", go.Figure()
    values = serie["valor"].values.astype(float)
    scaler = MinMaxScaler()
    scaled = scaler.fit_transform(values.reshape(-1, 1)).flatten()
    X, y = [], []
    for i in range(lookback, len(scaled)):
        X.append(scaled[i - lookback:i])
        y.append(scaled[i])
    X, y = np.array(X), np.array(y)
    X = X.reshape((X.shape[0], X.shape[1], 1))
    split = int(len(X) * 0.75)
    X_train, X_test = X[:split], X[split:]
    y_train, y_test = y[:split], y[split:]
    model = Sequential([
        Input(shape=(lookback, 1)),
        LSTM(32, return_sequences=True),
        Dropout(0.2),
        LSTM(16),
        Dropout(0.2),
        Dense(1)
    ])
    model.compile(optimizer="adam", loss="mse")
    es = EarlyStopping(patience=5, restore_best_weights=True)
    model.fit(X_train, y_train, epochs=epochs, batch_size=4, validation_split=0.15,
              callbacks=[es], verbose=0)
    pred_scaled = model.predict(X_test, verbose=0).flatten()
    pred = scaler.inverse_transform(pred_scaled.reshape(-1, 1)).flatten()
    real = scaler.inverse_transform(y_test.reshape(-1, 1)).flatten()
    rmse = np.sqrt(mean_squared_error(real, pred))
    last = scaled[-lookback:].tolist()
    future = []
    for _ in range(5):
        x_in = np.array(last[-lookback:]).reshape(1, lookback, 1)
        p = model.predict(x_in, verbose=0)[0, 0]
        future.append(p)
        last.append(p)
    future = scaler.inverse_transform(np.array(future).reshape(-1, 1)).flatten()
    anios_fut = list(range(int(serie["anio"].max()) + 1, int(serie["anio"].max()) + 6))
    texto = f"**LSTM – {depto} | {indicador}**\n\nRMSE test: {rmse:,.2f}\nPredicción 5 años: {dict(zip(anios_fut, future.round(1)))}"
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=serie["anio"], y=serie["valor"], name="Histórico", mode="lines+markers"))
    anios_test = serie["anio"].values[-len(real):]
    fig.add_trace(go.Scatter(x=anios_test, y=pred, name="Predicción test", mode="lines+markers"))
    fig.add_trace(go.Scatter(x=anios_fut, y=future, name="Forecast futuro", mode="lines+markers",
                             line=dict(dash="dash")))
    fig.update_layout(title=f"LSTM Forecast – {depto}", template="plotly_white",
                      xaxis_title="Año", yaxis_title="Valor")
    return texto, fig

def prediccion_y_simulacion(panel, target, features, anio_min, anio_max, shock_var, shock_pct, horizon=5):
    if panel.empty or not target or not features:
        return "Configure target y features.", go.Figure(), go.Figure()
    d = panel[(panel["anio"] >= anio_min) & (panel["anio"] <= anio_max)].dropna(subset=[target] + features)
    if len(d) < 25:
        return "Muestra insuficiente.", go.Figure(), go.Figure()
    X = d[features]
    y = d[target]
    model = GradientBoostingRegressor(n_estimators=80, max_depth=4, random_state=42)
    model.fit(X, y)
    last = d.sort_values("anio").groupby("anio")[features + [target]].mean().iloc[-1]
    baseline = []
    current = last[features].copy()
    for h in range(horizon):
        pred = model.predict(current.values.reshape(1, -1))[0]
        baseline.append(pred)
        current = current * 1.01
    shocked = last[features].copy()
    if shock_var in shocked.index:
        shocked[shock_var] *= (1 + shock_pct / 100)
    scenario = []
    current = shocked.copy()
    for h in range(horizon):
        pred = model.predict(current.values.reshape(1, -1))[0]
        scenario.append(pred)
        current = current * 1.01
    anios = list(range(int(d["anio"].max()) + 1, int(d["anio"].max()) + horizon + 1))
    texto = f"**Simulación de política**\n\nShock: {shock_var} {shock_pct:+.1f}%\nTarget: {target}\n\n"
    texto += pd.DataFrame({"Año": anios, "Baseline": baseline, "Con shock": scenario,
                           "Diferencia": np.array(scenario) - np.array(baseline)}).round(2).to_markdown(index=False)
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=anios, y=baseline, name="Baseline", mode="lines+markers"))
    fig.add_trace(go.Scatter(x=anios, y=scenario, name=f"Shock {shock_var} {shock_pct:+.0f}%",
                             mode="lines+markers", line=dict(dash="dash")))
    fig.update_layout(title="Simulación de política", template="plotly_white",
                      xaxis_title="Año", yaxis_title=target)
    imp = pd.Series(model.feature_importances_, index=features).sort_values(ascending=True)
    fig_imp = px.bar(x=imp.values, y=imp.index, orientation="h", title="Importancia de variables (GBM)",
                     template="plotly_white")
    return texto, fig, fig_imp

def interpretabilidad(panel, target, features, anio_min, anio_max):
    if panel.empty or not target or not features:
        return "Configure variables.", go.Figure()
    d = panel[(panel["anio"] >= anio_min) & (panel["anio"] <= anio_max)].dropna(subset=[target] + features)
    if len(d) < 20:
        return "Muestra insuficiente.", go.Figure()
    X = d[features]
    y = d[target]
    model = RandomForestRegressor(n_estimators=100, max_depth=5, random_state=42)
    model.fit(X, y)
    perm = permutation_importance(model, X, y, n_repeats=15, random_state=42)
    imp_df = pd.DataFrame({
        "feature": features,
        "importance_mean": perm.importances_mean,
        "importance_std": perm.importances_std
    }).sort_values("importance_mean", ascending=True)
    fig = go.Figure()
    fig.add_trace(go.Bar(
        x=imp_df["importance_mean"], y=imp_df["feature"], orientation="h",
        error_x=dict(type="data", array=imp_df["importance_std"]),
        marker_color="#1f77b4"
    ))
    fig.update_layout(title="Permutation Importance", template="plotly_white",
                      xaxis_title="Importancia", height=420)
    texto = "**Interpretabilidad automatizada**\n\nMétodo: Permutation Importance (Random Forest).\n\n"
    texto += imp_df.round(4).to_markdown(index=False)
    if HAS_SHAP:
        try:
            explainer = shap.TreeExplainer(model)
            shap_values = explainer.shap_values(X)
            mean_abs = np.abs(shap_values).mean(axis=0)
            texto += "\n\n**SHAP mean |valor|:**\n" + pd.Series(mean_abs, index=features).sort_values(ascending=False).round(4).to_markdown()
        except Exception:
            pass
    return texto, fig

