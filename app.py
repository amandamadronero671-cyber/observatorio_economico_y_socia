def eda_outliers(df, indicador, anio_min, anio_max, metodo="IQR"):
    d = filtrar(df, None, indicador, anio_min, anio_max)
    if d.empty or indicador == "Todos":
        return "Seleccione un indicador específico.", go.Figure()
    vals = d["valor"].dropna()
    if metodo == "IQR":
        q1, q3 = vals.quantile(0.25), vals.quantile(0.75)
        iqr = q3 - q1
        lower, upper = q1 - 1.5 * iqr, q3 + 1.5 * iqr
        outliers = d[(d["valor"] < lower) | (d["valor"] > upper)]
    else:
        z = np.abs(stats.zscore(vals))
        outliers = d.loc[vals.index[z > 3]]
    texto = f"**Outliers detectados ({metodo}): {len(outliers)}**\n\n" + outliers.head(20).to_markdown(index=False)
    fig = px.scatter(d, x="anio", y="valor", color="departamento",
                     title=f"Valores y outliers – {indicador}", template="plotly_white")
    if not outliers.empty:
        fig.add_trace(go.Scatter(x=outliers["anio"], y=outliers["valor"],
                                 mode="markers", marker=dict(symbol="x", size=12, color="red"),
                                 name="Outlier"))
    return texto, fig

def mineria_clustering(panel, anio_ref, n_clusters=4, metodo="KMeans"):
    if panel.empty:
        return "Panel vacío.", go.Figure(), go.Figure()
    d = panel[panel["anio"] == anio_ref].copy()
    cols = [c for c in d.columns if c not in ["departamento", "anio"] and d[c].notna().sum() > 5]
    if len(cols) < 2 or len(d) < n_clusters:
        return "Datos insuficientes para clustering.", go.Figure(), go.Figure()
    X = d[cols].fillna(d[cols].median())
    scaler = StandardScaler()
    Xs = scaler.fit_transform(X)
    if metodo == "KMeans":
        model = KMeans(n_clusters=n_clusters, random_state=42, n_init=10)
        labels = model.fit_predict(Xs)
        sil = silhouette_score(Xs, labels) if n_clusters > 1 else 0
    elif metodo == "Hierarchical":
        model = AgglomerativeClustering(n_clusters=n_clusters)
        labels = model.fit_predict(Xs)
        sil = silhouette_score(Xs, labels) if n_clusters > 1 else 0
    else:
        model = DBSCAN(eps=1.2, min_samples=2)
        labels = model.fit_predict(Xs)
        n_clusters = len(set(labels)) - (1 if -1 in labels else 0)
        sil = silhouette_score(Xs, labels) if n_clusters > 1 and -1 not in labels else 0
    d["cluster"] = labels
    texto = f"**Método: {metodo} | Clusters: {n_clusters} | Silhouette: {sil:.3f}**\n\n"
    texto += d.groupby("cluster")[cols].mean().round(2).to_markdown()
    pca = PCA(n_components=2)
    coords = pca.fit_transform(Xs)
    d["PC1"] = coords[:, 0]
    d["PC2"] = coords[:, 1]
    fig_sc = px.scatter(d, x="PC1", y="PC2", color="cluster", text="departamento",
                        title=f"Clustering {metodo} (PCA) – {anio_ref}",
                        template="plotly_white", color_continuous_scale="Viridis")
    fig_sc.update_traces(textposition="top center", textfont_size=9)
    perfil = d.groupby("cluster")[cols].mean().reset_index().melt(id_vars="cluster")
    fig_radar = px.bar(perfil, x="variable", y="value", color="cluster", barmode="group",
                       title="Perfil medio de clusters", template="plotly_white")
    fig_radar.update_layout(xaxis_tickangle=-30)
    return texto, fig_sc, fig_radar

def analisis_pca(panel, anio_min, anio_max, n_comp=3):
    if panel.empty:
        return "Panel vacío.", go.Figure(), go.Figure()
    d = panel[(panel["anio"] >= anio_min) & (panel["anio"] <= anio_max)].copy()
    cols = [c for c in d.columns if c not in ["departamento", "anio"] and d[c].notna().sum() > 10]
    if len(cols) < 2:
        return "Insuficientes variables.", go.Figure(), go.Figure()
    X = d[cols].fillna(d[cols].median())
    scaler = StandardScaler()
    Xs = scaler.fit_transform(X)
    n_comp = min(n_comp, len(cols), Xs.shape[0])
    pca = PCA(n_components=n_comp)
    scores = pca.fit_transform(Xs)
    var_exp = pca.explained_variance_ratio_
    texto = f"**Varianza explicada acumulada:** {var_exp.cumsum().round(3).tolist()}\n\n"
    loadings = pd.DataFrame(pca.components_.T, index=cols, columns=[f"PC{i+1}" for i in range(n_comp)])
    texto += "**Cargas (loadings):**\n\n" + loadings.round(3).to_markdown()
    fig_scree = go.Figure()
    fig_scree.add_trace(go.Bar(x=[f"PC{i+1}" for i in range(len(var_exp))], y=var_exp, name="Var. individual"))
    fig_scree.add_trace(go.Scatter(x=[f"PC{i+1}" for i in range(len(var_exp))], y=var_exp.cumsum(),
                                   mode="lines+markers", name="Acumulada", yaxis="y2"))
    fig_scree.update_layout(title="Scree plot", yaxis=dict(title="Proporción"),
                            yaxis2=dict(title="Acumulada", overlaying="y", side="right"),
                            template="plotly_white")
    d_plot = d.copy()
    d_plot["PC1"] = scores[:, 0]
    d_plot["PC2"] = scores[:, 1] if n_comp > 1 else 0
    fig_bi = px.scatter(d_plot, x="PC1", y="PC2",
                        color="departamento" if d_plot["departamento"].nunique() <= 15 else None,
                        title="Proyección PC1 vs PC2", template="plotly_white")
    return texto, fig_scree, fig_bi

def ml_regresion(panel, target_col, features, anio_min, anio_max, modelo="Ridge", alpha=1.0):
    if panel.empty or not target_col or not features:
        return "Seleccione target y features.", go.Figure(), ""
    d = panel[(panel["anio"] >= anio_min) & (panel["anio"] <= anio_max)].copy()
    cols = [target_col] + features
    d = d.dropna(subset=cols)
    if len(d) < 20:
        return "Muestra insuficiente (<20 observaciones).", go.Figure(), ""
    X = d[features]
    y = d[target_col]
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.25, random_state=42)
    scaler = StandardScaler()
    X_train_s = scaler.fit_transform(X_train)
    X_test_s = scaler.transform(X_test)
    models = {
        "Ridge": Ridge(alpha=alpha),
        "Lasso": Lasso(alpha=alpha, max_iter=5000),
        "ElasticNet": ElasticNet(alpha=alpha, l1_ratio=0.5, max_iter=5000),
        "SVR": SVR(kernel="rbf", C=1.0, epsilon=0.1),
        "RandomForest": RandomForestRegressor(n_estimators=100, random_state=42, max_depth=6),
        "GradientBoosting": GradientBoostingRegressor(n_estimators=100, random_state=42, max_depth=4),
        "OLS": LinearRegression()
    }
    model = models.get(modelo, Ridge(alpha=alpha))
    model.fit(X_train_s, y_train)
    y_pred = model.predict(X_test_s)
    rmse = np.sqrt(mean_squared_error(y_test, y_pred))
    mae = mean_absolute_error(y_test, y_pred)
    r2 = r2_score(y_test, y_pred)
    texto = f"**Modelo: {modelo}**\n\n- RMSE: {rmse:,.2f}\n- MAE: {mae:,.2f}\n- R²: {r2:.4f}\n- N train/test: {len(X_train)}/{len(X_test)}\n\n"
    if hasattr(model, "coef_"):
        coefs = pd.Series(model.coef_, index=features).sort_values(key=abs, ascending=False)
        texto += "**Coeficientes:**\n\n" + coefs.round(4).to_markdown()
    elif hasattr(model, "feature_importances_"):
        imp = pd.Series(model.feature_importances_, index=features).sort_values(ascending=False)
        texto += "**Importancia de variables:**\n\n" + imp.round(4).to_markdown()
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=y_test, y=y_pred, mode="markers", name="Predichos",
                             marker=dict(size=8, opacity=0.7)))
    lims = [min(y_test.min(), y_pred.min()), max(y_test.max(), y_pred.max())]
    fig.add_trace(go.Scatter(x=lims, y=lims, mode="lines", name="Ideal", line=dict(dash="dash", color="red")))
    fig.update_layout(title=f"{modelo}: Real vs Predicho", xaxis_title="Real", yaxis_title="Predicho",
                      template="plotly_white")
    try:
        perm = permutation_importance(model, X_test_s, y_test, n_repeats=10, random_state=42)
        imp_df = pd.DataFrame({"feature": features, "importance": perm.importances_mean}).sort_values("importance", ascending=False)
        texto += "\n\n**Permutation Importance:**\n\n" + imp_df.round(4).to_markdown(index=False)
    except Exception:
        pass
    return texto, fig, ""

def modelo_var_vec(panel, deptos, variables, maxlags=2, tipo="VAR"):
    if panel.empty or len(variables) < 2:
        return "Seleccione al menos 2 variables.", go.Figure(), ""
    d = panel.copy()
    if deptos and "Todos" not in deptos:
        d = d[d["departamento"].isin(deptos)]
    ts = d.groupby("anio")[variables].mean().dropna().sort_index()
    if len(ts) < maxlags + 5:
        return f"Serie demasiado corta ({len(ts)} obs).", go.Figure(), ""
    def is_stationary(series):
        try:
            return adfuller(series.dropna())[1] < 0.05
        except Exception:
            return False
    ts_diff = ts.copy()
    for col in variables:
        if not is_stationary(ts[col]):
            ts_diff[col] = ts[col].diff()
    ts_diff = ts_diff.dropna()
    texto = f"**Observaciones usadas:** {len(ts_diff)}\n\n"
    if tipo == "VAR":
        try:
            model = VAR(ts_diff)
            res = model.fit(maxlags=maxlags, ic="aic")
            texto += f"**Orden seleccionado (AIC):** {res.k_ar}\n\n" + str(res.summary())
            irf = res.irf(10)
            fig = go.Figure()
            for i, shock in enumerate(variables):
                for j, resp in enumerate(variables):
                    fig.add_trace(go.Scatter(y=irf.irfs[:, j, i], name=f"{resp} ← {shock}", line=dict(width=1.5)))
            fig.update_layout(title="Funciones de Impulso-Respuesta (IRF)", template="plotly_white",
                              xaxis_title="Periodos", yaxis_title="Respuesta")
            return texto[:8000], fig, ""
        except Exception as e:
            return f"Error VAR: {e}", go.Figure(), ""
    else:
        try:
            rank_test = select_coint_rank(ts, det_order=0, k_ar_diff=maxlags, method="trace")
            rank = rank_test.rank
            texto += f"**Rango de cointegración (Johansen):** {rank}\n\n"
            if rank == 0:
                return texto + "No hay cointegración → use VAR en diferencias.", go.Figure(), ""
            model = VECM(ts, k_ar_diff=maxlags, coint_rank=rank, deterministic="ci")
            res = model.fit()
            texto += str(res.summary())
            fig = go.Figure()
            resid = res.resid
            for i, col in enumerate(variables):
                fig.add_trace(go.Scatter(y=resid[:, i], name=f"Resid {col}", mode="lines"))
            fig.update_layout(title="Residuos VECM", template="plotly_white")
            return texto[:8000], fig, ""
        except Exception as e:
            return f"Error VECM: {e}", go.Figure(), ""

